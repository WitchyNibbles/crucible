def test_default_subagent_worker_rejects_unsupported_language(tmp_path):
    worker = DefaultSubagentWorker()
    with __import__("pytest").raises(ValueError, match="Unsupported language for DefaultSubagentWorker: 'rust'"):
        worker.run_language_task("task", "rust", {"repo_root": tmp_path / "repo"})


def test_default_subagent_worker_rejects_out_of_tree_paths(tmp_path):
    repo_root = tmp_path / "repo"
    repo_root.mkdir()

    assert not DefaultSubagentWorker._is_out_of_tree_rel(
        repo_root, "src/engineering/backend/python/app.py"
    )
    assert DefaultSubagentWorker._is_out_of_tree_rel(
        repo_root, "src/../../evil/app.py"
    )


def test_default_subagent_worker_defaults_discipline_and_layer(tmp_path):
    worker = DefaultSubagentWorker()
    result = worker.run_language_task(
        "task",
        "python",
        {"repo_root": tmp_path / "repo"},
    )

    assert result.metadata["discipline"] == "engineering"
    assert result.metadata["layer"] == "backend"


def test_default_subagent_worker_writes_files_to_repo_root(tmp_path):
    repo_root = tmp_path / "repo"
    repo_root.mkdir()

    worker = DefaultSubagentWorker()
    result = worker.run_language_task(
        "generate python app",
        "python",
        {"repo_root": repo_root, "discipline": "engineering", "layer": "backend"},
    )

    app = repo_root / "src/engineering/backend/python/app.py"
    readme = repo_root / "src/engineering/backend/python/README.md"

    assert result.metadata["real"] is True
    assert result.metadata["written"] == ["README.md", "app.py"]
    assert app.exists()
    assert readme.exists()
    assert "def main() -> None:" in app.read_text()
    assert "## Python stub" in readme.read_text()
    assert readme.read_text().startswith(ARTIFACT_HEADER)


