"""crucible/runner.py — execution harness for the CTO dev team waterfall.

This module turns tier prompts into real work products, writes them to disk,
runs exhaustive audits, loops on FAIL findings, and only signs off when every
gate passes.

No scaffolds. No placeholder folders. Real artifacts only:
  - code files
  - test files
  - config files
  - schemas
  - docs
"""

